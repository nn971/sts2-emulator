#!/usr/bin/env python3
"""Compare xUnit TRX results without disguising inherited failures as regressions.

Input is generated by dotnet test --logger trx. Baseline should be an actual
run against the intended base commit, not a historical failure count.
"""
import argparse
import json
import sys
import xml.etree.ElementTree as ET
from collections import Counter
from pathlib import Path


def load(paths):
    result = {}
    for name in paths:
        root = ET.parse(name).getroot()
        ns = {"t": "http://microsoft.com/schemas/VisualStudio/TeamTest/2010"}
        definitions = {}
        for node in root.findall(".//t:UnitTest", ns):
            test_id = node.get("id")
            method = node.find("t:TestMethod", ns)
            if method is not None:
                definitions[test_id] = (
                    method.get("className", "") + "." + method.get("name", "")
                )
        for node in root.findall(".//t:UnitTestResult", ns):
            key = definitions.get(node.get("testId"), node.get("testName", ""))
            if not key:
                raise ValueError("TRX result without an identifiable test")
            status = node.get("outcome", "Unknown")
            if key in result and result[key] != status:
                raise ValueError("Conflicting outcomes for " + key)
            result[key] = status
    return result


def classify(current, baseline):
    old_failed = {k for k, v in baseline.items() if v == "Failed"}
    now_failed = {k for k, v in current.items() if v == "Failed"}
    common = set(current) & set(baseline)
    return {
        "current": dict(Counter(current.values())),
        "baseline": dict(Counter(baseline.values())),
        "new_failures": sorted(k for k in common if k in now_failed and k not in old_failed),
        "inherited_failures": sorted(k for k in common if k in now_failed and k in old_failed),
        "fixed_failures": sorted(k for k in common if k not in now_failed and k in old_failed),
        "unclassified_new_tests_failed": sorted(now_failed - set(baseline)),
        "missing_from_current": sorted(set(baseline) - set(current)),
        "new_tests": sorted(set(current) - set(baseline)),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--current", nargs="+", required=True, type=Path)
    parser.add_argument("--baseline", nargs="+", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--require-no-regressions", action="store_true")
    args = parser.parse_args()
    current = load(args.current)
    if args.baseline:
        report = classify(current, load(args.baseline))
        fail = bool(report["new_failures"] or report["unclassified_new_tests_failed"])
    else:
        report = {
            "current": dict(Counter(current.values())),
            "baseline_status": "MISSING: do not label failures as inherited",
            "unclassified_failures": sorted(k for k, v in current.items() if v == "Failed"),
        }
        fail = bool(report["unclassified_failures"])
    data = json.dumps(report, indent=2, sort_keys=True) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(data, encoding="utf-8")
    print(data)
    return int(args.require_no_regressions and fail)


if __name__ == "__main__":
    sys.exit(main())
